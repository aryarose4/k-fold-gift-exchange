// k-Fold Gift Exchange Generator — display layer.
// ES module importing ./core.js and ./crypto.js. No frameworks, no deps.

import { generateAssignment, validateAssignment } from "./core.js";
import {
  affineEncrypt,
  elgamalEncryptRowsChunked,
  elgamalKeypair,
  encodeMessage,
  parseShareString,
  parseToken,
} from "./crypto.js";

// ---------------------------------------------------------------------------
// State
// ---------------------------------------------------------------------------

let result = null;         // { names, k, assignments } from the last Generate
let mode = "public";       // "public" | "secret" | "secure" (results mode)
let lastMessage = "";      // encoded public message (secret mode)
let lastKeys = [];         // affine key tokens, parallel to result.names
let secretCache = null;    // { sig, message, keys } — avoids re-encrypting on toggles
let renderSeq = 0;         // guards async renders against later mode switches
// Keypairs the organizer generated on a participant's behalf (double-blind
// mode), keyed by participant name: name -> { priv, pub }.
let organizerKeys = new Map();

const $ = (id) => document.getElementById(id);

// ---------------------------------------------------------------------------
// Name entry
// ---------------------------------------------------------------------------

function readRows() {
  const out = [];
  document.querySelectorAll("#ge-name-list .ge-name-row").forEach((row) => {
    const nameInput = row.querySelector(".ge-name-input");
    const pubEl = row.querySelector(".ge-pub-text");
    const name = nameInput.value.trim();
    if (!name) return;
    out.push({ name, pub: pubEl.dataset.token || "", nameInput, pubEl });
  });
  return out;
}

function updatePubDisplay(row) {
  const span = row.querySelector(".ge-pub-text");
  const tok = span.dataset.token || "";
  const generated = span.dataset.generated === "1";
  if (tok) {
    span.textContent = tok;
  } else {
    span.textContent = "No public key yet";
  }
  span.classList.toggle("ge-pub-missing", !tok);
  span.classList.toggle("ge-pub-generated", Boolean(tok) && generated);
  row.classList.toggle("ge-has-key", Boolean(tok));
}

function updateRowDisplay(row) {
  const name = row.querySelector(".ge-name-input").value.trim();
  const prev = row.dataset.name || "";
  row.querySelector(".ge-name-text").textContent = name || "(Unnamed)";
  // Keep an organizer-generated keypair attached to the row's (renamed) name
  // so it is not pruned away and its private key stays distributable.
  if (prev && prev !== name && organizerKeys.has(prev)) {
    const kp = organizerKeys.get(prev);
    organizerKeys.delete(prev);
    if (name) organizerKeys.set(name, kp);
  }
  row.dataset.name = name;
  updatePubDisplay(row);
}

// A participant's public key is shown only when it arrived explicitly: as a
// pasted Name:PublicKey share line, or as a key the organizer generated. The
// browser does not cache keypairs, so a typed name with no share line is always
// flagged as missing a key.

// Generate a keypair on behalf of a participant who never sent one. The
// organizer then hands them the private key after Generate.
function generateRowKeys(row) {
  const inp = row.querySelector(".ge-name-input");
  const name = inp.value.trim();
  if (!name) {
    inp.focus();
    return;
  }
  const { priv, pub } = elgamalKeypair();
  organizerKeys.set(name, { priv, pub });
  const span = row.querySelector(".ge-pub-text");
  span.dataset.token = pub;
  span.dataset.generated = "1";
  updateRowDisplay(row);
  syncState();
}

function setEditing(row, on) {
  row.classList.toggle("ge-editing", on);
  row.querySelector(".ge-edit").textContent = on ? "Done" : "Edit";
  if (on) row.querySelector(".ge-name-input").focus();
}

function addNameRow(value = "", pubValue = "") {
  const list = $("ge-name-list");
  const row = document.createElement("div");
  row.className = "ge-name-row";

  const text = document.createElement("span");
  text.className = "ge-name-text";

  const inp = document.createElement("input");
  inp.type = "text";
  inp.className = "ge-name-input";
  inp.placeholder = "Participant name";
  inp.value = value;
  inp.setAttribute("aria-label", "Participant name");

  // The public key is shown as plain text (double-blind mode only); it is
  // filled from a pasted Name:PublicKey line or generated by the organizer.
  const pub = document.createElement("span");
  pub.className = "ge-pub-text";
  pub.dataset.token = pubValue || "";
  pub.setAttribute("aria-label", "Public key");

  const genKeys = document.createElement("button");
  genKeys.type = "button";
  genKeys.className = "ge-btn ge-btn-small ge-genkeys";
  genKeys.textContent = "Generate Keys";
  genKeys.title = "Generate a keypair for this participant";
  genKeys.addEventListener("click", () => generateRowKeys(row));

  const edit = document.createElement("button");
  edit.type = "button";
  edit.className = "ge-btn ge-btn-small ge-edit";
  edit.textContent = "Edit";
  edit.addEventListener("click", () => {
    const on = !row.classList.contains("ge-editing");
    setEditing(row, on);
    if (!on) {
      updateRowDisplay(row);
      syncState();
    }
  });

  const del = document.createElement("button");
  del.type = "button";
  del.className = "ge-btn ge-btn-small ge-del";
  del.textContent = "Delete";
  del.setAttribute("aria-label", "Delete participant");
  del.addEventListener("click", () => {
    row.remove();
    syncState();
  });

  inp.addEventListener("input", () => {
    updateRowDisplay(row);
    syncState();
  });

  row.append(text, inp, pub, genKeys, edit, del);
  list.appendChild(row);
  updateRowDisplay(row);
  return inp;
}

// Names are separated by semicolons; a single name is the one-entry case.
// An entry may also be a "<name>:<public key>" share string from a
// participant, which fills in both the name and the key at once.
function splitNames(text) {
  return text
    .split(";")
    .map((s) => s.trim())
    .filter(Boolean);
}

// Case-insensitive lookup of an existing participant row by name.
function findRowByName(name) {
  const target = name.toLowerCase();
  let found = null;
  document.querySelectorAll("#ge-name-list .ge-name-row").forEach((row) => {
    if (found) return;
    if (row.querySelector(".ge-name-input").value.trim().toLowerCase() === target) {
      found = row;
    }
  });
  return found;
}

function addFromInput() {
  const input = $("ge-add-input");
  const entries = splitNames(input.value);
  if (!entries.length) return;
  for (const entry of entries) {
    // A "<name>:<public key>" share string from a participant fills in the
    // key. Names may not contain a colon, so the first colon is always the
    // separator and this is safe in every mode.
    const share = parseShareString(entry);
    if (!share) {
      addNameRow(entry);
      continue;
    }
    // If the participant is already listed (added earlier by name, or with a
    // generated key), just drop their real key in; otherwise add a new row.
    const existing = findRowByName(share.name);
    if (existing) {
      const name = existing.querySelector(".ge-name-input").value.trim();
      const pubEl = existing.querySelector(".ge-pub-text");
      const prev = pubEl.dataset.token;
      // Share lines are not authenticated, so replacing an already-set key is
      // explicit: never silently reassign an existing participant.
      if (prev && prev !== share.token &&
          !window.confirm("Replace the existing public key for " + name + "?")) {
        continue;
      }
      organizerKeys.delete(name);
      delete pubEl.dataset.generated;
      pubEl.dataset.token = share.token;
      updateRowDisplay(existing);
    } else {
      addNameRow(share.name, share.token);
    }
  }
  input.value = "";
  syncState();
  input.focus();
}

// ---------------------------------------------------------------------------
// Validation + k slider
// ---------------------------------------------------------------------------

function syncState() {
  const rows = readRows();
  const names = rows.map((r) => r.name);
  const n = names.length;
  const kSlider = $("ge-k");
  kSlider.max = String(Math.max(1, n - 1));
  if (parseInt(kSlider.value, 10) > n - 1) kSlider.value = kSlider.max;

  const errs = [];

  // Duplicate detection (case-insensitive).
  const seen = new Map();
  rows.forEach((r) => {
    const v = r.name.toLowerCase();
    const rowEl = r.nameInput.parentElement;
    if (seen.has(v)) {
      r.nameInput.classList.add("ge-invalid");
      rowEl.classList.add("ge-invalid");
      if (!seen.get(v)) seen.set(v, true);
    } else {
      r.nameInput.classList.remove("ge-invalid");
      rowEl.classList.remove("ge-invalid");
      seen.set(v, false);
    }
  });
  if ([...seen.values()].some(Boolean)) errs.push("Duplicate names are not allowed.");
  if (n < 2) errs.push("Need at least 2 participants.");

  // Public keys matter only in double-blind mode.
  const showPubs = mode === "secure";
  $("ge-add-input").placeholder = showPubs
    ? "Enter participant public keys"
    : "Name, or semicolon-separated names";
  $("ge-add-hint").style.display = showPubs ? "none" : "";
  document.querySelectorAll("#ge-name-list .ge-name-row").forEach((row) => {
    row.classList.toggle("ge-secure", showPubs);
    updatePubDisplay(row);
  });
  $("ge-secure-link").style.display = showPubs ? "" : "none";
  if (showPubs) {
    // A blank key is fine: the organizer can generate one for a participant
    // who never sent a key (either with the row button or automatically at
    // Generate). Only a pasted-but-invalid key is an error.
    let badPub = false;
    rows.forEach((r) => {
      let ok = true;
      if (r.pub) {
        try {
          ok = parseToken(r.pub).tier === "p";
        } catch (e) {
          ok = false;
        }
      }
      r.pubEl.classList.toggle("ge-invalid", !ok);
      if (!ok) badPub = true;
    });
    if (badPub) errs.push("One or more public keys are invalid. Re-paste the Name:PublicKey line.");
  }

  $("ge-generate").disabled = errs.length > 0;
  $("ge-error").textContent = errs[0] || "";
  $("ge-k-label").textContent =
    n >= 2
      ? `k = ${kSlider.value} (each gives and receives ${kSlider.value} gift${kSlider.value == 1 ? "" : "s"})`
      : "k";
}

// ---------------------------------------------------------------------------
// Rendering results
// ---------------------------------------------------------------------------

function renderPublic() {
  const host = $("ge-public-out");
  host.innerHTML = "";
  const table = document.createElement("table");
  table.className = "ge-table";
  const thead = table.createTHead();
  const hr = thead.insertRow();
  for (const h of ["Giver", "Gives to"]) {
    const th = document.createElement("th");
    th.textContent = h;
    hr.appendChild(th);
  }
  const tbody = table.createTBody();
  result.assignments.forEach((row, i) => {
    const tr = tbody.insertRow();
    tr.insertCell().textContent = result.names[i];
    tr.insertCell().textContent = row.map((j) => result.names[j]).join(", ");
  });
  host.appendChild(table);
}

// Personalized links open the standalone decrypt page with the message and
// key pre-filled, so the generator page's own URL never matters.
function decryptPageUrl() {
  const a = $("ge-decrypt-link");
  if (a && a.href) return a.href.split("#")[0];
  return location.origin + location.pathname;
}

function buildLink(message, key) {
  let frag = "ge=" + encodeURIComponent(message);
  if (key) frag += "&k=" + encodeURIComponent(key);
  return decryptPageUrl() + "#" + frag;
}

// One row of a key list: name + private token + Copy Key, plus an optional
// Copy Link (message + key) button. Shared by the per-person secret keys and
// the organizer-generated keys so the two lists cannot drift apart.
function appendKeyRow(host, name, token, showLink = true) {
  const row = document.createElement("div");
  row.className = "ge-key-row";

  const nm = document.createElement("span");
  nm.className = "ge-key-name";
  nm.textContent = name;

  const tok = document.createElement("code");
  tok.className = "ge-key-token";
  tok.textContent = token;

  const copyBtn = document.createElement("button");
  copyBtn.type = "button";
  copyBtn.className = "ge-btn ge-btn-small";
  copyBtn.textContent = "Copy Key";
  copyBtn.addEventListener("click", () =>
    copyText(token, $("ge-copy-status"), "Copied key for " + name + ".")
  );

  row.append(nm, tok, copyBtn);

  if (showLink) {
    const linkBtn = document.createElement("button");
    linkBtn.type = "button";
    linkBtn.className = "ge-btn ge-btn-small";
    linkBtn.textContent = "Copy Link";
    linkBtn.addEventListener("click", () =>
      copyText(buildLink(lastMessage, token), $("ge-copy-status"), "Copied link for " + name + ".")
    );
    row.append(linkBtn);
  }

  host.appendChild(row);
}

function renderKeys() {
  const host = $("ge-keys");
  host.innerHTML = "";
  if (mode === "secure") {
    // Double-blind mode: participants keep their own keys, so there is no
    // per-person key list here; organizer-generated keys are listed below.
    $("ge-keys-block").style.display = "none";
    return;
  }
  $("ge-keys-block").style.display = "";
  result.names.forEach((name, i) => appendKeyRow(host, name, lastKeys[i]));
}

// Double-blind mode shares one ready link instead of the raw public message:
// opening it fills the decrypt page's message box. The organizer-generated
// participants then only need the private key they are sent.
function renderPublicLink() {
  const linkBlock = $("ge-link-block");
  const msgBlock = $("ge-message-block");
  if (!linkBlock || !msgBlock) return;
  const doubleBlind = mode === "secure";
  linkBlock.style.display = doubleBlind ? "" : "none";
  msgBlock.style.display = doubleBlind ? "none" : "";
  if (doubleBlind) $("ge-public-link").href = buildLink(lastMessage);
}

// Double-blind mode with organizer-generated keys: the participant has no
// other copy, so the organizer must hand them the private key (or the ready
// link) after the assignments are generated.
function renderOrganizerKeys() {
  const block = $("ge-organizer-keys-block");
  const host = $("ge-organizer-keys");
  if (!block || !host) return;
  host.innerHTML = "";
  const names = result ? result.names.filter((name) => organizerKeys.has(name)) : [];
  if (mode !== "secure" || !names.length) {
    block.style.display = "none";
    return;
  }
  block.style.display = "";
  for (const name of names) appendKeyRow(host, name, organizerKeys.get(name).priv, false);
}

// Encrypt the current assignment for Secret mode and paint the outputs.
// Re-uses a cached ciphertext when the assignment and tier are unchanged,
// so switching modes/tiers does not re-run the (O(n*k)) encryption.
async function renderSecret(seq) {
  const k = result.k;
  const secure = mode === "secure";
  const pubByName = new Map(readRows().map((r) => [r.name, r.pub]));
  const pubs = secure
    ? result.names.map((name) => {
        const pasted = pubByName.get(name);
        if (pasted) return pasted;
        const made = organizerKeys.get(name);
        return made ? made.pub : "";
      })
    : null;
  if (secure) {
    // Don't attempt encryption with missing/bad keys; show an actionable
    // message instead of leaving the results panel blank.
    const bad = pubs.some((p) => {
      try {
        return parseToken(p).tier !== "p";
      } catch (e) {
        return true;
      }
    });
    if (bad) {
      $("ge-public-out").innerHTML = "";
      $("ge-secret-out").style.display = "none";
      $("ge-error").textContent =
        "Add or generate a public key for every participant, then press Generate.";
      return;
    }
  }
  const sig =
    (secure ? "e|" : "a|") +
    JSON.stringify(result.names) +
    "|" +
    JSON.stringify(result.assignments) +
    "|" +
    (secure ? JSON.stringify(pubs) : "");

  if (secretCache && secretCache.sig === sig) {
    lastMessage = secretCache.message;
    lastKeys = secretCache.keys;
  } else {
    try {
      if (secure) {
        const { message } = await elgamalEncryptRowsChunked(result.names, k, result.assignments, pubs);
        lastMessage = encodeMessage(message);
        lastKeys = [];
      } else {
        const { message, keys } = affineEncrypt(result.names, k, result.assignments);
        lastMessage = encodeMessage(message);
        lastKeys = keys;
      }
      secretCache = { sig, message: lastMessage, keys: lastKeys };
    } catch (e) {
      $("ge-error").textContent = e.message;
      $("ge-secret-out").style.display = "none";
      return;
    }
  }
  // A newer render (e.g. a mode switch during the awaited encryption)
  // superseded this one; don't paint stale output over it.
  if (seq !== renderSeq) return;
  $("ge-message").value = lastMessage;
  renderPublicLink();
  renderKeys();
  renderOrganizerKeys();
  $("ge-public-out").innerHTML = "";
  $("ge-secret-out").style.display = "";
}

async function renderResults() {
  if (!result) return;
  const seq = ++renderSeq;
  if (mode === "public") {
    $("ge-secret-out").style.display = "none";
    renderPublic();
  } else {
    await renderSecret(seq);
  }
  if (seq !== renderSeq) return;
  $("ge-results-wrap").style.display = "";
}

// ---------------------------------------------------------------------------
// Copy helpers
// ---------------------------------------------------------------------------

async function copyText(text, statusEl, okMsg) {
  try {
    await navigator.clipboard.writeText(text);
    if (statusEl) {
      statusEl.textContent = okMsg;
      setTimeout(() => (statusEl.textContent = ""), 3000);
    }
  } catch (e) {
    const fb = $("ge-copy-fallback");
    if (fb) {
      fb.style.display = "";
      fb.value = text;
      fb.select();
    }
    if (statusEl) statusEl.textContent = "Copy failed. Select and copy manually.";
  }
}

