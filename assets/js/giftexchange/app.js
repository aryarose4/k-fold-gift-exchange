// Drop keys for participants no longer in the roster (deleted or renamed).
function pruneOrganizerKeys(map, names) {
  const keep = new Set(names);
  const next = new Map();
  for (const [name, kp] of map) if (keep.has(name)) next.set(name, kp);
  return next;
}

// Give a keypair to every row that has no key, and regenerate one whose
// generated key can no longer be matched to a stored private key (e.g. the
// row was renamed). Called before any Double-Blind encryption.
function ensureSecureKeys(rows) {
  for (const r of rows) {
    const orphaned = r.pubEl.dataset.generated === "1" && !organizerKeys.has(r.name);
    if (r.pub && !orphaned) continue;
    const { priv, pub } = elgamalKeypair();
    organizerKeys.set(r.name, { priv, pub });
    r.pubEl.dataset.token = pub;
    r.pubEl.dataset.generated = "1";
  }
}

async function generate() {
  const rows = readRows();
  const names = rows.map((r) => r.name);
  const k = parseInt($("ge-k").value, 10);
  let res;
  try {
    res = generateAssignment(names, k);
    if (!validateAssignment(res)) throw new Error("internal validation failed");
  } catch (e) {
    $("ge-error").textContent = e.message;
    $("ge-results-wrap").style.display = "none";
    return;
  }
  result = res;
  secretCache = null;

  // Double-blind mode: fill in keys for anyone who never sent one, so the
  // organizer can still run the exchange; they get the distribution prompt
  // after the assignments appear.
  organizerKeys = pruneOrganizerKeys(organizerKeys, names);
  if (mode === "secure") ensureSecureKeys(rows);

  $("ge-error").textContent = "";
  $("ge-generate").disabled = true;
  try {
    await renderResults();
  } finally {
    syncState();
  }
}

// ---------------------------------------------------------------------------
// Setup
// ---------------------------------------------------------------------------

export function activate() {
  $("ge-add").addEventListener("click", addFromInput);
  $("ge-add-input").addEventListener("keydown", (e) => {
    if (e.key === "Enter") {
      e.preventDefault();
      addFromInput();
    }
  });
  $("ge-generate").addEventListener("click", generate);
  $("ge-k").addEventListener("input", syncState);
  $("ge-copy-message").addEventListener("click", () =>
    copyText(lastMessage, $("ge-copy-status"), "Copied Public Message.")
  );
  $("ge-copy-public-link").addEventListener("click", () =>
    copyText(buildLink(lastMessage), $("ge-copy-status"), "Copied share link.")
  );

  $("ge-mode").addEventListener("change", (e) => {
    const next = e.target.value;
    if (next === mode) return;
    // Changing the mode must discard the generated assignments, or the
    // organizer could generate in one mode and peek in another. Entering
    // Double Blind also resets the roster, because every participant has to
    // supply a public key (re-add them as Name:PublicKey share lines).
    const resetRoster = next === "secure" && mode !== "secure";
    const hasRoster = !resetRoster || readRows().length > 0;
    if (result || (resetRoster && hasRoster)) {
      const warn =
        "The roster will be reset for public key entry.";
      const keep = "The roster will be preserved.";
      const msg =
        (result ? "Changing the mode resets the generated assignments. " : "") +
        (resetRoster ? warn : keep);
      if (!window.confirm(msg)) {
        e.target.value = mode;
        return;
      }
    }
    mode = next;
    // Drop all generated state so nothing stale can be revealed.
    result = null;
    secretCache = null;
    lastMessage = "";
    lastKeys = [];
    renderSeq++;
    if (resetRoster) {
      $("ge-name-list").innerHTML = "";
      organizerKeys = new Map();
    }
    $("ge-results-wrap").style.display = "none";
    $("ge-public-out").innerHTML = "";
    $("ge-secret-out").style.display = "none";
    $("ge-message").value = "";
    syncState();
  });

  syncState();
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", activate);
} else {
  activate();
}
