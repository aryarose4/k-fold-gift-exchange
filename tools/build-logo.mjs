import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

// Keep the approved transparent master untouched; change only derived paint.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const imageDir = path.join(root, 'assets/img');
const master = fs.readFileSync(path.join(imageDir, 'gift-exchange-logo.svg'), 'utf8').replace(/\r\n?/g, '\n');
if (!/^<svg\b[^>]*xmlns="http:\/\/www\.w3\.org\/2000\/svg"[^>]*>/.test(master)) {
  throw new Error('Expected an SVG root with the default SVG namespace.');
}
if (!master.includes('  <defs>')) throw new Error('Expected the master logo definitions.');
const notice = '  <!-- Generated by tools/build-logo.mjs from gift-exchange-logo.svg. -->\n';
const annotate = svg => svg.replace('  <defs>', notice + '  <defs>');
const light = annotate(master.replace(/(fill|stroke)="#fff"/g, '$1="#212529"'));
const dark = annotate(master);
const adaptive = master.replace(/(fill|stroke)="#fff"/g, '$1="currentColor"').replace('  <defs>', notice +
  '  <style>\n' +
  '    :root { color: #212529; }\n' +
  '    @media (prefers-color-scheme: dark) {\n' +
  '      :root { color: #fff; }\n' +
  '    }\n' +
  '  </style>\n' +
  '  <defs>');
for (const [name, svg] of [['light', light], ['dark', dark], ['tile', adaptive]]) {
  const filename = 'gift-exchange-logo-' + name + '.svg';
  fs.writeFileSync(path.join(imageDir, filename), svg);
  console.log('Generated assets/img/' + filename);
}
