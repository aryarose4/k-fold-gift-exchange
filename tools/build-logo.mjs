import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

// Keep the transparent approved master untouched; derive a light-theme-safe tile.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const masterPath = path.join(root, 'assets/img/gift-exchange-logo.svg');
const tilePath = path.join(root, 'assets/img/gift-exchange-logo-tile.svg');
const master = fs.readFileSync(masterPath, 'utf8').replace(/\r\n?/g, '\n');
if (!/^<svg\b[^>]*xmlns="http:\/\/www\.w3\.org\/2000\/svg"[^>]*>/.test(master)) {
  throw new Error('Expected an SVG root with the default SVG namespace.');
}
const tile = master.replace(/  <defs>/, '  <!-- Generated by tools/build-logo.mjs from gift-exchange-logo.svg. -->\n  <rect width="512" height="512" rx="32" fill="#1c1c1d"/>\n  <defs>');
if (tile === master) throw new Error('Expected the master logo definitions.');
fs.writeFileSync(tilePath, tile);
console.log('Generated assets/img/gift-exchange-logo-tile.svg');
